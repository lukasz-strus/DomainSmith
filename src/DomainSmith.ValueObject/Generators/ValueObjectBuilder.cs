using System.Text;
using DomainSmith.Abstraction.Common.Models;
using DomainSmith.Abstraction.Generators;

namespace DomainSmith.ValueObject.Generators;

internal sealed class ValueObjectBuilder : BaseBuilder
{
    private readonly StringBuilder _extensionName = new();
    private readonly StringBuilder _extensionReference = new();
    private List<(string Type, string Name)> _properties = [];
    private bool _isResultPattern = true;

    internal void SetExtensionName(string className)
    {
        _extensionName.Clear();
        _extensionName.Append(className);
        _extensionName.Append("Extensions");
    }

    internal void SetExtensionReference(string? @namespace, string className)
    {
        _extensionReference.Clear();

        if (!string.IsNullOrEmpty(@namespace))
        {
            _extensionReference.Append(@namespace);
            _extensionReference.Append(".");
        }

        _extensionReference.Append(className);
        _extensionReference.Append("Extensions");
    }

    internal void SetProperties(List<PropertyInfo> properties)
        => _properties = [.. properties.Select(p => (p.Type, p.Name))];

    internal void SetIsResultPattern(bool isResultPattern)
        => _isResultPattern = isResultPattern;

    protected override string BuildSource()
    {
        ApplyConditionalUsings();

        var parts = BuildConstructionParts();
        var signature = BuildCreateSignature();

        return RenderSource(parts, signature);
    }

    private void ApplyConditionalUsings()
    {
        if (_isResultPattern)
            Usings.Append("\nusing DomainSmith.Abstraction.Core.Result;");
    }

    private ConstructionParts BuildConstructionParts()
    {
        var ctorParams = new List<string>();
        var ctorAssignments = new List<string>();
        var createParams = new List<string>();
        var createArgs = new List<string>();
        var onCreatingRefParams = new List<string>();
        var onCreatingParams = new List<string>();

        foreach (var (type, name) in _properties)
        {
            var paramName = name.ToLower();

            ctorParams.Add($"{type} {paramName}");
            ctorAssignments.Add($"{name} = {paramName};");

            createParams.Add($"{type} {paramName}");
            createArgs.Add(paramName);

            onCreatingRefParams.Add($"ref {paramName}");
            onCreatingParams.Add($"ref {type} {paramName}");
        }

        return new ConstructionParts(
            string.Join(", ", ctorParams),
            string.Join("\n\t\t", ctorAssignments),
            string.Join(", ", createParams),
            string.Join(", ", createArgs),
            string.Join(", ", onCreatingRefParams),
            string.Join(", ", onCreatingParams)
        );
    }

    private CreateSignature BuildCreateSignature()
    {
        var createResultType = _isResultPattern ? $"Result<{ClassName}>" : $"{ClassName}?";
        var createReturnSuccess = _isResultPattern ? "return Result.Success(result);" : "return result;";
        var createReturnFailure = _isResultPattern
            ? $"return Result.Failure<{ClassName}>(error);"
            : "return null;";

        var refDeclParams = _isResultPattern ? "ref bool canCreate, ref Error error" : "ref bool canCreate";
        var refParams = _isResultPattern ? "ref canCreate, ref error" : "ref canCreate";
        var refVars = _isResultPattern
            ? "bool canCreate = true;\n\t\tError error = Error.None;"
            : "bool canCreate = true;";

        return new CreateSignature(
            createResultType,
            createReturnSuccess,
            createReturnFailure,
            refDeclParams,
            refParams,
            refVars
        );
    }

    private string RenderSource(ConstructionParts parts, CreateSignature signature)
    {
        return $$"""
                 // <auto-generated/>
                 {{Usings}}

                 {{Namespace}}

                 partial record {{ClassName}}
                 {
                     private {{ClassName}}({{parts.CtorParams}})
                     {
                         {{parts.CtorAssignments}}
                     }

                     public static {{signature.CreateResultType}} Create({{parts.CreateParams}})
                     {
                         {{signature.RefVars}}

                         OnCreating({{parts.OnCreatingRefParams}}, {{signature.RefParams}});
                         
                         var result = new {{ClassName}}({{parts.CreateArgs}});

                         OnCreated(result, {{signature.RefParams}});
                         if (!canCreate) {{signature.CreateReturnFailure}}

                         {{signature.CreateReturnSuccess}}
                     }

                     static partial void OnCreating({{parts.OnCreatingParams}}, {{signature.RefDeclParams}});
                     static partial void OnCreated({{ClassName}} instance, {{signature.RefDeclParams}});
                 }
                 """;
    }

    private readonly record struct ConstructionParts(
        string CtorParams,
        string CtorAssignments,
        string CreateParams,
        string CreateArgs,
        string OnCreatingRefParams,
        string OnCreatingParams);

    private readonly record struct CreateSignature(
        string CreateResultType,
        string CreateReturnSuccess,
        string CreateReturnFailure,
        string RefDeclParams,
        string RefParams,
        string RefVars);

    protected override bool IsEmpty() =>
        Usings.Length == 0 &&
        Namespace.Length == 0 &&
        ClassName.Length == 0;
}